using CodigoActivo.Domain.BlockedData;
using CodigoActivo.Infrastructure.Database.Configurations;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace CodigoActivo.Infrastructure.BlockedData;

/// <summary>
/// Defines the Entity Framework mapping for the consultations of the blocked data. The account
/// that opened a consultation has no foreign key: the record of the access outlives the account.
/// The consultations whose notice is pending are indexed in the order they are told.
/// </summary>
public sealed class BlockedDataConsultationConfiguration
    : IEntityTypeConfiguration<BlockedDataConsultation>
{
    /// <summary>
    /// Configures the database mapping for the consultations of the blocked data.
    /// </summary>
    /// <param name="builder">Entity Framework builder used to configure the mapped type.</param>
    public void Configure(EntityTypeBuilder<BlockedDataConsultation> builder)
    {
        builder.HasNoHistory();
        builder.HasKey(c => c.Id);

        builder.Property(c => c.Id).ValueGeneratedNever();
        builder.Property(c => c.OfficerId).IsRequired();
        builder.Property(c => c.Authority).HasConversion<string>().HasMaxLength(32).IsRequired();
        builder
            .Property(c => c.Reference)
            .HasMaxLength(BlockedDataConsultation.ReferenceMaxLength)
            .IsRequired();
        builder.Property(c => c.OpenedAt).IsRequired();
        builder.Property(c => c.ExpiresAt).IsRequired();
        builder.Property(c => c.NoticePending).IsRequired();

        builder.HasIndex(c => c.OpenedAt);
        builder
            .HasIndex(c => c.OpenedAt, nameof(BlockedDataConsultation.NoticePending))
            .HasDatabaseName("ix_blocked_data_consultations_notice_pending")
            .HasFilter("notice_pending");
    }
}

/// <summary>
/// Defines the Entity Framework mapping for the accounts a consultation found.
/// </summary>
public sealed class BlockedDataFindingConfiguration : IEntityTypeConfiguration<BlockedDataFinding>
{
    /// <summary>
    /// Configures the database mapping for the accounts a consultation found.
    /// </summary>
    /// <param name="builder">Entity Framework builder used to configure the mapped type.</param>
    public void Configure(EntityTypeBuilder<BlockedDataFinding> builder)
    {
        builder.ToTable("blocked_data_findings");
        builder.HasNoHistory();
        builder.HasKey(f => new { f.ConsultationId, f.AccountId });
        builder.Property(f => f.FoundAt).IsRequired();

        builder
            .HasOne<BlockedDataConsultation>()
            .WithMany(c => c.Findings)
            .HasForeignKey(f => f.ConsultationId)
            .OnDelete(DeleteBehavior.Cascade);
    }
}

/// <summary>
/// Defines the Entity Framework mapping for the extracts a consultation took.
/// </summary>
public sealed class BlockedDataExtractConfiguration : IEntityTypeConfiguration<BlockedDataExtract>
{
    /// <summary>
    /// Name of the shadow key, generated by the database in insertion order.
    /// </summary>
    public const string Sequence = "Id";

    /// <summary>
    /// Configures the database mapping for the extracts a consultation took.
    /// </summary>
    /// <param name="builder">Entity Framework builder used to configure the mapped type.</param>
    public void Configure(EntityTypeBuilder<BlockedDataExtract> builder)
    {
        builder.ToTable("blocked_data_extracts");
        builder.HasNoHistory();
        builder.Property<long>(Sequence).ValueGeneratedOnAdd();
        builder.HasKey(Sequence);

        builder.Property(e => e.AccountId).IsRequired();
        builder.PrimitiveCollection(e => e.Entities).IsRequired();
        builder.Property(e => e.EntryCount).IsRequired();
        builder.Property(e => e.IncludesCurrentData).IsRequired();
        builder.Property(e => e.ExtractedAt).IsRequired();

        builder
            .HasOne<BlockedDataConsultation>()
            .WithMany(c => c.Extracts)
            .HasForeignKey(e => e.ConsultationId)
            .OnDelete(DeleteBehavior.Cascade);
    }
}
